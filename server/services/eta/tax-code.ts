/** تصنيف الحساب إلى سطر فاتورة: مدين/دائن/محايد وتحديد الضريبة */
export interface EtaTaxDecision {
  taxType: EtaTaxType;
  rate: number;
  subType?: string;
}

/**
 * حدد نوع الضريبة وقيمتها حسب نوع الحساب أو وصف البند.
 * تُستخدم عند بناء الفاتورة من القيود/الإيصالات.
 */
export function decideTaxType(
  accountType: string,
  description: string,
  amount: number,
  opts?: { salary?: boolean }
): EtaTaxDecision {
  const text = `${description || ''}`.toLowerCase();
  const isSalary =
    (opts?.salary ?? false) ||
    /مرتب|راتب|أجر|مكافأة|كسب عمل|أجور/.test(text);
  const isInsurance = /تأمين|معاش|اشتراك تأمين/.test(text);
  const isMembership = /اشتراك عضوية|رسوم عضوية|اشتراكات/.test(text);
  const isExpense = accountType === 'EXPENSE';
  const isRevenue = accountType === 'REVENUE';

  if (isSalary && amount > 0) {
    // ضريبة كسب العمل تُخصم من المرتب
    return { taxType: 'K1', rate: 0, subType: 'K1' };
  }
  if (isInsurance) return { taxType: 'Z1', rate: 0 };
  if (isMembership) return { taxType: 'Z1', rate: 0 }; // رسوم عضوية لا تخضع للضريبة
  if (isExpense && isInsurance) return { taxType: 'Z2', rate: 0 };
  if (isRevenue) {
    // إيرادات النقابة (اشتراكات) معفاة عادةً
    return { taxType: 'Z1', rate: 0 };
  }
  return { taxType: 'T1', rate: 14 };
}

/** هل سطر البند يخضع لضريبة القيمة المضافة؟ */
export function isTaxable(decision: EtaTaxDecision): boolean {
  return decision.taxType === 'T1' || decision.taxType === 'T2' || decision.taxType === 'T3';
}
