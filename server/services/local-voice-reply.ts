/** رد صوتي محلي يعمل بدون GEMINI_API_KEY. */
export function localVoiceReply(prompt: string): string {
  const text = String(prompt || '').trim();
  const q = text.toLowerCase();
  if (!text) return 'أنا أسمعك. قل سؤالك وسأرد عليك الآن.';
  if (/تسمع|سمعني|تستجيب|صوت|شغال|تعمل|رد/.test(q)) {
    return 'نعم، أسمعك. المحادثة الصوتية مفعّلة، وهذا رد مباشر على كلامك.';
  }
  if (/سلام|مرحب|أهل|اهلا|صباح|مساء|hello|hi/.test(q)) {
    return 'أهلاً بك. المساعد الصوتي يعمل. اسألني عن قيد، أو رصيد، أو بند في اللائحة.';
  }
  if (/إيراد|ايراد|مصروف|فائض|ميزانية|رصيد|حساب/.test(q)) {
    return 'المساعد المالي يعمل. اسأل عن بند محدد، مثل الإيرادات أو حساب المدينين، وسأشرح الرصيد والخطوة التالية داخل النظام.';
  }
  if (/قيد|يومية|مدين|دائن/.test(q)) {
    return 'لأي قيد: اجعل مجموع المدين يساوي مجموع الدائن، ثم راجع الحساب من دليل الحسابات قبل الاعتماد.';
  }
  if (/لائحة|صرف|هدية|مشتريات/.test(q)) {
    return 'اللائحة مفعّلة في النظام. راجع حد الصرف النقدي والمستندات قبل اعتماد أي مبلغ كبير.';
  }
  if (/ويندوز|powershell|نظام التشغيل|registry|مفتاح/.test(q)) {
    return 'لا أنفّذ أوامر على الجهاز من هذه المحادثة. أقدر أساعدك في المحاسبة والتقارير والقيود.';
  }
  return `سمعتك تقول: ${text}. المساعد الصوتي يعمل الآن. اسأل عن قيد أو رصيد أو اللائحة لأكمل الإجابة.`;
}
