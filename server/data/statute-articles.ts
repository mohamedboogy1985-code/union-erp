export const MEMBERSHIP_ACTIONS: MembershipAction[] = [
  'CREATE',
  'ACTIVATE',
  'REINSTATE',
  'SUSPEND',
  'WRITE_OFF',
  'WITHDRAW',
];

export const isMembershipAction = (action: string): action is MembershipAction =>
  (MEMBERSHIP_ACTIONS as string[]).includes(action);

export const inRuleScope = (
  rule: StatuteRuleDefinition,
  action: MembershipAction | GovernanceAction,
): boolean => {
  if (!rule.appliesTo) return true;
  if (isMembershipAction(action)) {
    return rule.appliesTo.membership ? rule.appliesTo.membership.includes(action) : false;
  }
  return rule.appliesTo.governance ? rule.appliesTo.governance.includes(action) : false;
};

export const statuteRuleById = (ruleId: string): StatuteRuleDefinition | undefined =>
  STATUTE_ACTIVATED_RULES.find((r) => r.id === ruleId);

export const STATUTE_KEYWORDS_INDEX: Record<string, number[]> = STATUTE_ARTICLES.reduce<
  Record<string, number[]>
>((acc, article) => {
  for (const term of [article.title, ...article.keywords]) {
    const key = term.trim();
    acc[key] = [...(acc[key] ?? []), article.number];
  }
  return acc;
}, {});
